import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const read = file => readFileSync(new URL(`../${file}`, import.meta.url), "utf8");
const source = ts.transpileModule(read("lib/community-drafts.ts"), { compilerOptions: { module: ts.ModuleKind.ES2022 } }).outputText;
const store = await import(`data:text/javascript;base64,${Buffer.from(source).toString("base64")}`);
const a = store.communityDraftKey("member-a", "reply", "room-a");
const b = store.communityDraftKey("member-b", "reply", "room-a");
const other = store.communityDraftKey("member-a", "reply", "room-b");
assert.notEqual(a, b); assert.notEqual(a, other);
store.writeCommunityDraft(a, { body: "My unsent reply", step: 2 }, 1000);
assert.deepEqual(store.readCommunityDraft(a, 1001), { body: "My unsent reply", step: 2 });
assert.equal(store.readCommunityDraft(b, 1001), undefined);
const copy = store.readCommunityDraft(a, 1001); copy.body = "mutated";
assert.equal(store.readCommunityDraft(a, 1001).body, "My unsent reply");
store.removeCommunityDraft(a); assert.equal(store.readCommunityDraft(a, 1001), undefined);
store.writeCommunityDraft(a, "expired", 0);
assert.equal(store.readCommunityDraft(a, 8 * 60 * 60 * 1000), undefined);
store.writeCommunityDraft(a, "x".repeat(100001)); assert.equal(store.readCommunityDraft(a), undefined);
store.writeCommunityDraft(a, "private"); const epoch = store.communityDraftEpoch();
store.clearCommunityDrafts(); assert.equal(store.readCommunityDraft(a), undefined); assert.equal(store.communityDraftEpoch(), epoch + 1);
for (let n = 0; n < 101; n++) store.writeCommunityDraft(`bounded-${n}`, n);
assert.equal(store.readCommunityDraft("bounded-0"), undefined); assert.equal(store.readCommunityDraft("bounded-100"), 100);
store.clearCommunityDrafts();
const hook = read("lib/use-community-draft.ts");
assert(hook.includes('"beforeunload"') && hook.includes('event.preventDefault()') && hook.includes('state.key === key'));
assert(!read("lib/community-drafts.ts").includes("sessionStorage") && !read("lib/community-drafts.ts").includes("localStorage"));
const signout = read("components/auth/sign-out-button.tsx");
assert(signout.indexOf("clearCommunityDrafts();") < signout.indexOf('window.location.replace("/")'));
for (const file of ["components/member/community-feed.tsx", "components/member/community-reply-form.tsx", "components/member/community-gathering-discussion.tsx", "components/member/community-gathering-room.tsx", "components/member/community-gathering-video.tsx", "components/community/community-recording-form.tsx", "components/community/community-event-proposal-panel.tsx"]) assert(read(file).includes("communityDraftKey"), `Missing account-scoped draft integration: ${file}`);
assert(read("components/community/community-recording-form.tsx").includes("requestId: crypto.randomUUID()"));
assert(read("components/community/community-event-proposal-panel.tsx").includes("draftProposalId"));
const planner = read("components/community/community-event-proposal-panel.tsx");
assert(planner.indexOf("setEditingId(savedProposal)") < planner.indexOf('"publish_community_gathering"'), "Retain the saved draft ID before a publication attempt");
assert(read("components/member/community-reply-form.tsx").includes('if (await onSubmit(event)) clear("")'));
console.log("Draft store behaviour passed: account/room isolation, clone safety, cleanup, expiry and bounds. Navigation/reload source contracts passed; browser interaction acceptance remains separate.");
