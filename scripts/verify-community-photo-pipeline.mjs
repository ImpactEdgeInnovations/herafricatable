import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { readCommunityPhotoBody, communityPhotoRequestLimit } from "../lib/community-photo-body.mjs";
const source = path => readFileSync(new URL(`../${path}`, import.meta.url), "utf8");
const stream = chunks => new ReadableStream({ start(controller) { for (const chunk of chunks) controller.enqueue(Uint8Array.from(chunk)); controller.close(); } });
assert.deepEqual(await readCommunityPhotoBody(stream([[1, 2], [3]]), 3), Buffer.from([1, 2, 3]));
assert.equal((await readCommunityPhotoBody(stream([]), 3)).length, 0);
await assert.rejects(() => readCommunityPhotoBody(null), /Choose a photo/);
let cancelled = false;
const oversized = new ReadableStream({ start(controller) { controller.enqueue(new Uint8Array(4)); }, cancel() { cancelled = true; } });
await assert.rejects(() => readCommunityPhotoBody(oversized, 3), /smaller than 4 MB/);
assert(cancelled); assert(!oversized.locked);
assert(communityPhotoRequestLimit < 4500000);
const upload = source("app/api/community/photos/[id]/upload/route.ts");
for (const guard of ['request.headers.get("origin")', "auth.getUser()", "readCommunityPhotoBody(request.body)", "claim_community_photo_upload", "finish_community_photo_upload", "current.upload_token === token", "if (!removeError)", "upsert: false"]) assert(upload.includes(guard), guard);
assert(upload.indexOf('includes(current.status)') < upload.indexOf('current.upload_token === token'), "Lost finalisation responses must not delete saved files");
const delivery = source("app/api/community/photos/[id]/route.ts");
assert(delivery.includes('rpc("get_community_photo_file"'));
assert.equal(delivery.match(/await permission\(\)/g).length, 2);
assert(delivery.includes("private, no-store")); assert(!delivery.includes("createSignedUrl"));
const cleanup = source("lib/community-photo-cleanup.ts");
assert(cleanup.indexOf(".remove(") < cleanup.indexOf('rpc("finish_community_photo_cleanup"'));
assert(cleanup.includes("if (storageError) { failed++; continue; }"));
const sql = source("supabase/migrations/20261007160000_community_photo_upload_pipeline.sql");
for (const guard of ["as restrictive", "skip locked", "upload_attempts", "get_community_photo_file", "review_community_album_photo"]) assert(sql.toLowerCase().includes(guard), guard);
const ui = source("components/community/community-photo-albums.tsx");
for (const guard of ["Only Hosts can add photos", "Member photos need approval", "I have permission", "Retry unsaved photos", "clearDraft(emptyDraft)", "useCommunityFileGuard(unsavedFiles"]) assert(ui.includes(guard), guard);
assert(source("lib/use-community-file-guard.ts").includes("beforeunload"));
console.log("Photo pipeline checks passed: real bounded stream reads/cancellation and source contracts for upload, delivery, cleanup and Host controls. Live binary/browser acceptance remains separate.");
