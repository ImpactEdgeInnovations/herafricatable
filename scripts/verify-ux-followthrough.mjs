const ScrollableTabs = new Function('React','useCallback','useEffect','useRef','useState','ResizeObserver','window',`${compile(read('components/ui/scrollable-tabs.tsx'))};return ScrollableTabs;`)(React,fn=>fn,fn=>{if(runEffects)fn();},()=>({current:strip}),()=>[edgeState,value=>{edgeState=value;}],class {constructor(fn){resizeCallback=fn;}observe(){observed=true;}disconnect(){}},{addEventListener(){},removeEventListener(){}});
ScrollableTabs({activeKey:'people',label:'Community sections',children:null});
assert.equal(strip.scrollLeft,200,'Selected section aligns within the strip, not the page');
assert.deepEqual(edgeState,{before:true,after:true});assert(observed);
