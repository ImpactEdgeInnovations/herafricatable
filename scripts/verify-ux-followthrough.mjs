import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import ts from 'typescript';
const read = file => readFileSync(new URL(`../${file}`, import.meta.url), 'utf8');
const compile = source => ts.transpileModule(source.replace(/^import[\s\S]*?;\n/gm, '').replace(/^export /gm, ''), {compilerOptions:{jsx:ts.JsxEmit.React,target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.None}}).outputText;
let feedbackState = null;
const feedbackModule = new Function('React','useState',`${compile(read('components/ui/action-feedback.tsx'))};return {ActionFeedback,useActionFeedback};`)(React, () => [feedbackState, value => { feedbackState = value; }]);
let feedback = feedbackModule.useActionFeedback();
assert.equal(feedback.feedback,null);
assert.equal(renderToStaticMarkup(React.createElement(feedbackModule.ActionFeedback,{value:null})), '');
feedback.setMessage('Permission denied.');
assert.equal(feedbackState.tone,'error');
feedback.setMessage('Draft saved privately.','success');
assert.equal(feedbackState.tone,'success');
feedback.setMessage('Email waiting to send.','notice');
assert.equal(feedbackState.tone,'notice');
feedback.setMessage('');assert.equal(feedbackState,null);
for (const tone of ['success','error','notice']) {
  const html = renderToStaticMarkup(React.createElement(feedbackModule.ActionFeedback,{value:{message:'A result <script>bad</script>',tone},floating:true,onDismiss(){ }},React.createElement('a',{href:'#recent-invitations'},'Check invitations')));
  assert(html.includes(tone==='error'?'role="alert"':'role="status"'));
  assert(html.includes('&lt;script&gt;')&&!html.includes('<script>'));
  assert(html.includes('Dismiss this message')&&html.includes('href="#recent-invitations"'));
}

