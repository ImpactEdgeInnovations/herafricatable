async function functionInstalled(name) {
  const { error } = await service.rpc(name, { p_event_id: testEventId });
  if (!error || error.code === "P0001") return true;
  if (error.code === "PGRST202") return false;
  throw new Error(`Could not check ${name}: ${error.code || "network error"}`);
}

async function tableInstalled(name) {
  const { error } = await service.from(name).select("event_id").limit(0);
  if (!error) return true;
  if (error.code === "PGRST205") return false;
  throw new Error(`Could not check ${name}: ${error.code || "network error"}`);
}

async function invitationCryptoReady() {
  // A 64-character zero token cannot be generated by the random invitation
  // writer in any practical rehearsal. Previewing it exercises digest()
  // without opening or claiming a member's actual private invitation.
  const { data, error } = await service.rpc("preview_table_invitation", {
    p_token: "0".repeat(64),
  });
  if (error && ["PGRST202", "42883"].includes(error.code)) return false;
  if (error) throw new Error(`Could not check invitation preview: ${error.code || "network error"}`);
  return Array.isArray(data) && data.length === 0;
}

