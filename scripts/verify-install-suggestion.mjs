import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createInstallRequest, installPlatform, installSuggestionAllowed, INSTALL_PAUSE_MS } from '../lib/pwa-install.mjs';
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
assert.equal(installPlatform('iPhone'), 'ios');
assert.equal(installPlatform('Macintosh', 5), 'ios');
assert.equal(installPlatform('Macintosh', 0), 'desktop');
assert.equal(installPlatform('Android'), 'android');
assert.equal(installPlatform('Windows'), 'desktop');
assert.equal(INSTALL_PAUSE_MS, 604800000);
assert(installSuggestionAllowed('/events', null, 100));
assert(!installSuggestionAllowed('/events', '200', 100));
assert(installSuggestionAllowed('/events', '99', 100));
assert(installSuggestionAllowed('/home', 'invalid', 100));
for (const route of ['/sign-in', '/apply', '/onboarding', '/admin', '/messages', '/events/example/host', '/communities/example']) assert(!installSuggestionAllowed(route, null));
for (const outcome of ['accepted', 'dismissed']) {
  let calls = 0;
  const request = createInstallRequest({ prompt: async () => { calls++; }, userChoice: Promise.resolve({ outcome }) });
  assert.equal(await request.run(), outcome);
  assert.equal(await request.run(), 'instructions');
  assert.equal(calls, 1);
}
let calls = 0;
let release;
const request = createInstallRequest({ prompt: async () => { calls++; await new Promise(resolve => { release = resolve; }); }, userChoice: Promise.resolve({ outcome: 'accepted' }) });
const first = request.run();
assert.equal(await request.run(), 'instructions');
release();
assert.equal(await first, 'accepted');
assert.equal(calls, 1);
assert.equal(await createInstallRequest({ prompt: async () => { throw Error('browser refused'); }, userChoice: Promise.resolve({ outcome: 'dismissed' }) }).run(), 'error');
const provider = read('components/pwa/pwa-provider.tsx');
assert(provider.indexOf('setPrompt(null);', provider.indexOf('install: async')) < provider.indexOf('await prompt.run()'));
assert(provider.includes('installBusy.current') && provider.includes('finally'));
const suggestion = read('components/pwa/install-app.tsx');
assert(suggestion.includes('15000') && suggestion.includes('dialog[open]') && suggestion.includes('contenteditable'));
assert(suggestion.includes('Not now') && suggestion.includes('INSTALL_PAUSE_MS'));
assert(read('app/layout.tsx').includes('<InstallAppSuggestion />'));
console.log('Install suggestion behaviour passed: iOS/iPad/Android/desktop guidance, seven-day pause, safe routes, one-use/concurrent prompts and browser error recovery. Real device installation remains separate.');
