import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import ts from 'typescript';
const read=file=>readFileSync(new URL(`../${file}`,import.meta.url),'utf8');
const source=read('components/member/community-start-path.tsx').replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
const code=ts.transpileModule(source,{compilerOptions:{jsx:ts.JsxEmit.React,target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.None}}).outputText;
const StartPath=new Function('React','Link',`${code};return CommunityStartPath;`)(React,({href,children,...props})=>React.createElement('a',{href,...props},children));
const state={joined_at:'2026-10-08',has_introduction:false,has_contribution:true,has_accepted_connection:false,has_upcoming_registration:false,next_gathering_slug:'test',next_gathering_title:'Our next meeting',next_gathering_starts_at:'2026-10-09'};
